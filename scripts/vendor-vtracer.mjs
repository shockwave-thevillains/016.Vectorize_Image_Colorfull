#!/usr/bin/env node
/**
 * Generates a browser (ES module) build of vtracer from @visioncortex/vtracer.
 *
 * The npm package ships a wasm-bindgen "nodejs" target: the .wasm binary is
 * platform-neutral, only the last lines of the JS glue load it with
 * require('fs'). This script rewrites ONLY that loader into an async
 * `initVtracer(wasmUrl)` that uses fetch + WebAssembly.instantiate, and turns
 * the CommonJS exports into ES exports. The engine (and therefore the SVG
 * output) is byte-for-byte the same as the server/Node version.
 *
 * Output: src/vendor/vtracer/{vtracer_wasm.js, vtracer_wasm.d.ts, vtracer_wasm_bg.wasm}
 * Usage : npm run vendor:vtracer   (re-run after upgrading @visioncortex/vtracer)
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const pkgJsonPath = require.resolve('@visioncortex/vtracer/package.json');
const pkgDir = path.dirname(pkgJsonPath);
const { version } = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
const outDir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/vendor/vtracer');

let glue = readFileSync(path.join(pkgDir, 'pkg/vtracer_wasm.js'), 'utf8');

function replaceOnce(pattern, replacement, label) {
  const matches = glue.match(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'));
  if (!matches || matches.length !== 1) {
    throw new Error(`[vendor-vtracer] expected exactly 1 match for "${label}", found ${matches ? matches.length : 0}. ` +
      `The upstream glue changed — review scripts/vendor-vtracer.mjs.`);
  }
  glue = glue.replace(pattern, replacement);
}

replaceOnce(/^\/\* @ts-self-types=.*\*\/\n/m, '', 'ts-self-types header');
replaceOnce(/^exports\.vectorize_bytes = vectorize_bytes;\n/m, '', 'exports.vectorize_bytes');
replaceOnce(/^exports\.vectorize_rgba = vectorize_rgba;\n/m, '', 'exports.vectorize_rgba');
replaceOnce(
  /^const wasmPath = [\s\S]*?^wasm\.__wbindgen_start\(\);\s*$/m,
  `let wasm;

/** Load & instantiate the vtracer WebAssembly module (idempotent). */
export async function initVtracer(wasmUrl) {
    if (wasm) return;
    const res = await fetch(wasmUrl);
    if (!res.ok) throw new Error(\`Gagal memuat vtracer WASM (\${res.status})\`);
    const bytes = await res.arrayBuffer();
    const { instance } = await WebAssembly.instantiate(bytes, __wbg_get_imports());
    wasm = instance.exports;
    wasm.__wbindgen_start();
}

export { vectorize_bytes, vectorize_rgba };
`,
  'node fs loader'
);

if (/require\(|module\.exports|exports\./.test(glue)) {
  throw new Error('[vendor-vtracer] CommonJS/Node remnants left in glue — aborting.');
}

const header = `/* eslint-disable */
// AUTO-GENERATED by scripts/vendor-vtracer.mjs from @visioncortex/vtracer@${version}
// (wasm-bindgen glue, MIT OR Apache-2.0, https://github.com/visioncortex/vtracer).
// Only the Node fs loader was replaced with a browser fetch loader. Do not edit by hand.
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, 'vtracer_wasm.js'), header + glue);
copyFileSync(path.join(pkgDir, 'pkg/vtracer_wasm_bg.wasm'), path.join(outDir, 'vtracer_wasm_bg.wasm'));
writeFileSync(
  path.join(outDir, 'vtracer_wasm.d.ts'),
  `// AUTO-GENERATED by scripts/vendor-vtracer.mjs (@visioncortex/vtracer@${version})
export function initVtracer(wasmUrl: string): Promise<void>;
/** Vectorize a raw RGBA8 buffer (width * height * 4 bytes). Returns the SVG string. */
export function vectorize_rgba(data: Uint8Array, width: number, height: number, options: any): string;
/** Vectorize encoded image bytes (PNG/JPEG/GIF/BMP). Returns the SVG string. */
export function vectorize_bytes(data: Uint8Array, options: any): string;
`
);
console.log(`[vendor-vtracer] wrote browser build of @visioncortex/vtracer@${version} to ${path.relative(process.cwd(), outDir)}`);
